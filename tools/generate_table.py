"""Compile the editable UTF-8 translation dictionary into a C++ header."""
import json
import sys
from pathlib import Path


def generate(source: Path, destination: Path) -> None:
    entries = json.loads(source.read_text(encoding="utf-8"))
    if not isinstance(entries, dict) or not entries:
        raise ValueError("Translations must be a non-empty JSON object")
    rows = ["// Generated by tools/generate_table.py; edit translations/zh-CN.json.",
            "static const Translation kTranslations[] = {"]
    def cpp(value):
        if not isinstance(value, str) or "\0" in value:
            raise ValueError("Each source and translation must be a string without NUL")
        return '"' + "".join(f"\\x{b:02x}" for b in value.encode("utf-8")) + '"'
    for en, zh in sorted(entries.items(), key=lambda item: -len(item[0])):
        if en and en != zh:
            rows.append(f"    {{{cpp(en)}, {cpp(zh)}}},")
    rows.append("};")
    destination.parent.mkdir(parents=True, exist_ok=True)
    destination.write_text("\n".join(rows) + "\n", encoding="utf-8")


if __name__ == "__main__":
    generate(Path(sys.argv[1]), Path(sys.argv[2]))
